public class MiPrograma {
    public static void main(String[] args) {
        System.out.println(42);
        System.out.println(-7);
        System.out.println(5000000000L);
        System.out.println('Z');
        System.out.println(true);
        System.out.println(false);
        System.out.println("texto");
        System.out.println("");
        System.out.println();
        System.out.print(1);
        System.out.print(2L);
        System.out.print('3');
        System.out.print("4");
        System.out.print(true);
        System.out.println();
        System.out.println('a' + 'b');
        System.out.println((char) ('a' + 1));
        System.out.println('a' + "b");
        System.out.println(1 + 2 + "3");
        System.out.println("1" + 2 + 3);
        System.out.println(1 > 2);
        System.out.println(1 + 1 == 2);
        System.out.println("a" == "a");
        System.out.println(-(-5));
        System.out.println(- -5);
        System.out.println(+5);
        System.out.println(-'a');
        System.out.println(!true);
        System.out.println((long) 3);
        System.out.println(7 / 2);
        System.out.println(7L / 2);
        System.out.println(1_000_000);
        System.out.println(2147483647);
        System.out.println(-2147483648);
        System.out.println(9223372036854775807L);
        System.out.println(-9223372036854775808L);
        System.out.println('\n' + 0);
        System.out.println('\t' + 0);
        System.out.println('\\' + 0);
        System.out.println('\'' + 0);
        System.out.println("a\tb");
        System.out.println("comillas \" dentro");
        System.out.println("barra \\ dentro");
        System.out.print("sin salto al final");
    }
}
