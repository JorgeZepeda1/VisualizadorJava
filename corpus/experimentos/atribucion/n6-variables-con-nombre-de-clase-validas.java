import java.util.Scanner;

// Control: variables que se llaman como una clase, usadas con su propio tipo.
public class N6VariablesConNombreDeClaseValidas {
    public static void main(String[] args) {
        String String = "a";
        int n = String.length();
        Scanner Scanner = new Scanner(System.in);
        Scanner.close();
        int Math = 5;
        int y = Math + 1;
        String Integer = "7";
        int p = Integer.length();
        System.out.println(n + y + p);
    }
}
