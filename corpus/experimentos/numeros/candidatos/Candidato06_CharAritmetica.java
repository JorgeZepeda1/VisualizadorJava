public class Candidato06_CharAritmetica {
    public static void main(String[] args) {
        System.out.println('A' + 1);
        System.out.println((char) ('A' + 1));
        char c = 'A';
        c++;
        System.out.println(c);
        System.out.println('a' + 'b' + "");
        System.out.println("" + 'a' + 'b');
        System.out.println((char) -1 + 0);
    }
}
