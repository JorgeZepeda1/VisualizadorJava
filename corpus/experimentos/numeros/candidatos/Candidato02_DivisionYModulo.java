public class Candidato02_DivisionYModulo {
    public static void main(String[] args) {
        System.out.println(7 / 2);
        System.out.println(-7 / 2);
        System.out.println(7 / -2);
        System.out.println(-7 % 3);
        System.out.println(7 % -3);
        System.out.println(5 / 2.0);
        double d = 5 / 2;
        System.out.println(d);
    }
}
