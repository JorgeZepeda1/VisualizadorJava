public class Tipos {
    public static void main(String[] args) {
        byte pequeno = (byte) 200;
        short mediano = 1000;
        float decimal = 3.5f;
        long grande = 123456789012L;
        System.out.println("byte: " + pequeno);
        System.out.println("short: " + mediano);
        System.out.println("float: " + decimal);
        System.out.println("long: " + grande);
    }
}
