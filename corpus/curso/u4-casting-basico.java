public class CastingBasico {
    public static void main(String[] args) {
        double promedio = 8.75;
        int promedioRedondeado = (int) promedio;
        System.out.println("(int) 8.75 = " + promedioRedondeado);

        double promedio2 = 8.99;
        int promedioRedondeado2 = (int) promedio2;
        System.out.println("(int) 8.99 = " + promedioRedondeado2);
    }
}
