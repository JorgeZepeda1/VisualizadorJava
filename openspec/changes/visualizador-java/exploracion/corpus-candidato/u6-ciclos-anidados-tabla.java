public class CiclosAnidadosTabla {
    public static void main(String[] args) {
        for (int fila = 1; fila <= 3; fila++) {
            for (int columna = 1; columna <= 3; columna++) {
                System.out.print(fila * columna + " ");
            }
            System.out.println();
        }
    }
}
