public class flow02_switch_char {
    public static void main(String[] args) {
        char nota = 'B';
        switch (nota) {
            case 'A':
                System.out.println("Excelente");
                break;
            case 'B':
                System.out.println("Bien");
                break;
            default:
                System.out.println("Sin definir");
        }
    }
}
